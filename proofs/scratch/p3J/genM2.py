# img + core 1's node words (CUR/IDLE_THREAD = I1T, CUR/IDLE_SC = I1S), core 1's idle TCB I1T (kernelBase+0xB000:
# STATE 7, SC I1S, AFFINITY 1) and idle SC I1S (kernelBase+0xC000: CORE 1, TCB I1T, the idle SC's refill words),
# NUM_NODES 2; cores Csw = {0, 1}. Inside namespace JBootQ.M2 the copies' names win over JBootQ's (longest prefix).
import pathlib, sys
P = pathlib.Path
D = P('Fl4Proofs/P3')
files = ['Mem', 'Sched', 'Z', 'Cs', 'Inv', 'Lay', 'Blk', 'Live', 'JAt', 'U40']
I1T, I1S = 18446744071562113024, 18446744071562117120
NEW = [(18446744071562151360, f'{I1T}#u64'), (18446744071562151368, f'{I1T}#u64'),
       (18446744071562151384, f'{I1S}#u64'), (18446744071562151392, f'{I1S}#u64'),
       (I1T + 3328, '7#u64'), (I1T + 3464, f'{I1S}#u64'), (I1T + 3520, '1#u64'),
       (I1S + 16, '1#u64'), (I1S + 24, f'{I1T}#u64'), (I1S + 72, '2#u64'), (I1S + 88, '1#u64'),
       (I1S + 104, 'mpW'), (I1S + 112, 'mpW')]
def sub1(t, old, new):
    assert t.count(old) == 1, (old[:70], t.count(old))
    return t.replace(old, new)
over = {}
for a in sys.argv[1:]:
    k, v = a.split('=', 1); over[k] = P(v).read_text()
for f in files:
    t = (D / f'JBootQ{f}.lean').read_text()
    for g in files:
        t = t.replace(f'import Fl4Proofs.P3.JBootQ{g}\n', f'import Fl4Proofs.P3.JBootM2{g}\n')
    t = sub1(t, '\nnamespace Fl4Proofs.P3.JBootQ\n', '\nnamespace Fl4Proofs.P3.JBootQ.M2\n')
    t = sub1(t, '\nend Fl4Proofs.P3.JBootQ\n', '\nend Fl4Proofs.P3.JBootQ.M2\n')
    assert t.startswith('/-\n')
    t = ('/-\n**p3J gen 17 copy** of JBootQ%s (namespace `JBootQ.M2`, generated by scratch/p3J/genM2.py): the same\n'
         'proofs at the **2-core** boot witness `JBootQ.M2.w0` (JBootM2Mem: `JBootQ.img` plus core 1\'s node words, core 1\'s\n'
         'idle TCB `I1T` and idle SC `I1S` as FL4\'s `create_idle_thread` writes them, boot.rs l.684-704; `NUM_NODES` 2),\n'
         'cores `Csw = {0, 1}` (JBootM2Z). Core 1\'s idle objects are outside every ghost set, `H` and the spec state\n'
         '(the per-core projection, P3JMc). Original docstring:\n\n' % f) + t[3:]
    if f == 'Mem':
        t = sub1(t, '  if a = 18446744071562133504 then 1#u64 else\n', '  if a = 18446744071562133504 then 2#u64 else\n')
        new = ''.join(f'  if a = {a} then {v} else\n' for a, v in NEW)
        t = sub1(t, '  if a = 18446744071562134744 then 3#u64 else 0#u64\n',
                 '  if a = 18446744071562134744 then 3#u64 else\n' + new + '  0#u64\n')
        hs = ''.join(f'\n    (h{20+i} : a ≠ {a})' for i, (a, _) in enumerate(NEW))
        t = sub1(t, '    (h19 : a ≠ 18446744071562134744) :\n', '    (h19 : a ≠ 18446744071562134744)' + hs + ' :\n')
        rws = ''.join(f', if_neg h{20+i}' for i in range(len(NEW)))
        t = sub1(t, 'if_neg h18, if_neg h19]', 'if_neg h18, if_neg h19' + rws + ']')
    if f == 'Z':
        t = sub1(t, 'def Csw : Set U64 := {0#u64}', 'def Csw : Set U64 := {0#u64, 1#u64}')
    if f in ('Blk', 'Lay', 'Live'):
        t = sub1(t, 'import Fl4Proofs.P3.JBootM2Z\n', 'import Fl4Proofs.P3.JBootM2N1\n')
    if f == 'Blk':
        t = t.replace('JBootQ.tcbZ', 'M2.tcbZ')
        t = sub1(t, 'theorem memCs {c : U64} (h : c ∈ Csw) : c = 0#u64 := Set.mem_singleton_iff.mp h',
                 'theorem memCs {c : U64} (h : c ∈ Csw) : c = 0#u64 ∨ c = 1#u64 := h')
        t = sub1(t, '  nodes c hc := by rw [memCs hc]; exact nodePlaced_w0\n  cur := rfl\n  aff t ht := by rw [memT0 ht, aff_w0]; rfl\n',
                 '  nodes c hc := by rcases memCs hc with rfl | rfl; exacts [nodePlaced_w0, nodePlaced1]\n'
                 '  cur := Or.inl rfl\n  aff t ht := by rw [memT0 ht, aff_w0]; exact Or.inl rfl\n')
        t = sub1(t, 'scCore_w0]; exact ⟨rfl, rfl, rfl⟩', 'scCore_w0]; exact ⟨rfl, rfl, Or.inl rfl⟩')
        t = sub1(t, '  core c hc := by rw [memC0 hc, scCore_w0]; rfl', '  core c hc := by rw [memC0 hc, scCore_w0]; exact Or.inl rfl')
        t = sub1(t, '  ready c hc := by rw [memCs hc]; exact w0_schedCore.ready\n  release c hc := by rw [memCs hc]; exact w0_schedCore.release\n',
                 '  ready c hc := by rcases memCs hc with rfl | rfl; exacts [w0_schedCore.ready, ready1]\n'
                 '  release c hc := by rcases memCs hc with rfl | rfl; exacts [w0_schedCore.release, release1]\n')
        t = sub1(t, '    · rw [memCs hc, nodeBase_w0]; omega\n',
                 '    · rcases memCs hc with rfl | rfl\n      · rw [nodeBase_w0]; omega\n      · rw [nodeBase1]; omega\n')
        t = sub1(t, 'npl := fun c hc => by rw [memCs hc]; exact nodePlaced_w0',
                 'npl := fun c hc => by rcases memCs hc with rfl | rfl; exacts [nodePlaced_w0, nodePlaced1]')
        for a, b in [('troot_w0', 'troot1'), ('tmin_w0', 'tmin1'), ('dbg_w0', 'dbg1')]:
            t = sub1(t, f'by rw [memCs hc, {a}]; exact Or.inl rfl',
                     f'by rcases memCs hc with rfl | rfl <;> first | (rw [{a}]; exact Or.inl rfl) | (rw [{b}]; exact Or.inl rfl)')
        t = sub1(t, '      rw [memCs hc]\n      exact ⟨.leaf, {', '      rcases memCs hc with rfl | rfl <;>\n      exact ⟨.leaf, {')
        t = sub1(t, 'rep := TRB.Rep.leaf _ _ troot_w0', 'rep := TRB.Rep.leaf _ _ (by first | exact troot_w0 | exact troot1)')
        t = sub1(t, 'min := tmin_w0 }', 'min := (by first | exact tmin_w0 | exact tmin1) }')
    if f == 'Lay':
        t = sub1(t, '    rw [Csw, Set.mem_singleton_iff] at hc; subst hc\n    rw [nodeBase_w0]\n',
                 '    rcases memCs2 hc with rfl | rfl <;> (first | rw [nodeBase_w0] | rw [nodeBase1]) <;>\n')
    if f == 'Live':
        t = sub1(t, '    rw [Csw, Set.mem_singleton_iff] at hc; subst hc\n    exact dbgHead_w0\n',
                 '    rcases memCs2 hc with rfl | rfl\n    · exact dbgHead_w0\n    · exact dbg1\n')
    for k, v in over.items():
        if k.startswith(f + ':'):
            name = k.split(':', 1)[1]
            i = t.index(name); j = t.index('\n/--', i + 1) if '\n/--' in t[i+1:] else t.index('\nend', i)
            # replace from the docstring preceding `name` up to the next docstring
            s = t.rindex('\n/--', 0, i)
            t = t[:s] + '\n' + v.rstrip('\n') + '\n' + t[j:]
    (D / f'JBootM2{f}.lean').write_text(t)
print('ok')
