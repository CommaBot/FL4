# gen 15: the root-thread witness w1 / σ1 (JBoot1St … JBoot1JAt) copied onto FL4's boot IRQ layout, namespace
# Fl4Proofs.P3.JBootQ (which opens JBoot), as genQ.py did for w0: imports JBoot1X ↦ JBootQ1X, JBootX ↦ JBootQX,
# so `img`, `fInitASt`, `bootSt`, `w0`, … resolve to the JBootQ copies (current namespace wins over `open`).
#  * JBootQ1Mem.img1_zero: + the three IRQ-state words (passed to JBootQ.img_zero), w1_irqRel re-proved.
import pathlib
P = pathlib.Path
D = P('Fl4Proofs/P3')
files = ['St', 'Spec', 'Mem', 'Z', 'Cs', 'Lay', 'Inv', 'Blk', 'Live', 'JAt']
qfiles = ['St', 'Char', 'Mem', 'Sched', 'Z', 'Cs', 'Inv', 'Lay', 'Blk', 'Live', 'JAt']
A = [18446744071562134728, 18446744071562134736, 18446744071562134744]
def sub1(t, old, new):
    assert t.count(old) == 1, (old[:60], t.count(old))
    return t.replace(old, new)
for f in files:
    t = (D / f'JBoot1{f}.lean').read_text()
    for g in files:
        t = t.replace(f'import Fl4Proofs.P3.JBoot1{g}\n', f'import Fl4Proofs.P3.JBootQ1{g}\n')
    for g in qfiles:
        t = t.replace(f'import Fl4Proofs.P3.JBoot{g}\n', f'import Fl4Proofs.P3.JBootQ{g}\n')
    for line in t.splitlines():
        if line.startswith('import Fl4Proofs.P3.JBoot'):
            assert line.startswith('import Fl4Proofs.P3.JBootQ'), line
    t = sub1(t, '\nnamespace Fl4Proofs.P3.JBoot\n', '\nnamespace Fl4Proofs.P3.JBootQ\nopen Fl4Proofs.P3.JBoot\n')
    t = sub1(t, '\nend Fl4Proofs.P3.JBoot\n', '\nend Fl4Proofs.P3.JBootQ\n')
    assert 'JBoot.' not in t
    assert t.startswith('/-\n')
    t = ('/-\n**p3J gen 15 copy** of JBoot1%s (namespace `JBootQ`, generated by scratch/p3J/genQ1.py): the same proofs\n'
         'at the root-thread witness `JBootQ.w1` / `JBootQ.σ1` on FL4\'s boot IRQ layout (`JBootQ.fInitASt`, `JBootQ.img`:\n'
         'line 125 `IRQ_TIMER`, 126 / 127 `IRQ_IPI`; spec 125 `irqTimer`, 126 / 127 `irqReserved`). Original docstring:\n\n'
         % f) + t[3:]
    if f == 'Mem':
        t = sub1(t, '    (g16 : a ≠ 18446744071562096752) :\n',
                 f'    (g16 : a ≠ 18446744071562096752)\n    (g17 : a ≠ {A[0]})\n    (g18 : a ≠ {A[1]})\n'
                 f'    (g19 : a ≠ {A[2]}) :\n')
        t = sub1(t, 'exact img_zero g1 g2 g3 g4 g5 h1 g7 h2 g9 g10 g11 g12 g13 g14 g15 g16\n',
                 'exact img_zero g1 g2 g3 g4 g5 h1 g7 h2 g9 g10 g11 g12 g13 g14 g15 g16 g17 g18 g19\n')
        old = t[t.index('/-- **`IrqRel` at `w1`.** -/'):t.index('/-- **`IoRel` at `w1`.** -/')]
        t = t.replace(old, P('scratch/p3J/Q1irq.lean').read_text())
    (D / f'JBootQ1{f}.lean').write_text(t)
print('ok')
