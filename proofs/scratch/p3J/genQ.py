# gen 7: the jboot witness with FL4's boot IRQ layout. JBootChar/Mem/Sched/Z/Cs/Inv/Lay/Blk/Live/JAt copied
# verbatim into namespace Fl4Proofs.P3.JBootQ (which opens JBoot), with:
#  * JBootQSt.fInitASt = jboot's fInitASt with interruptStates 125 timer, 126/127 reserved (= SInvIB.fInitIpiASt),
#  * JBootQChar.bootSt with those interrupt states (initASt_eq dropped),
#  * JBootQMem.img with the IRQ-state words of lines 125 = IRQ_TIMER (2), 126/127 = IRQ_IPI (3)
#    (boot.rs init_irq_states), img_zero with the three addresses excluded, w0_irqRel re-proved.
import re, pathlib
P = pathlib.Path
D = P('Fl4Proofs/P3')
files = ['Char', 'Mem', 'Sched', 'Z', 'Cs', 'Inv', 'Lay', 'Blk', 'Live', 'JAt']
A = [18446744071562134728, 18446744071562134736, 18446744071562134744]
def sub1(t, old, new):
    assert t.count(old) == 1, (old[:60], t.count(old))
    return t.replace(old, new)
for f in files:
    t = (D / f'JBoot{f}.lean').read_text()
    t = t.replace('import Fl4Proofs.P3.JBootSt\n', 'import Fl4Proofs.P3.JBootQSt\n')
    for g in files:
        t = t.replace(f'import Fl4Proofs.P3.JBoot{g}\n', f'import Fl4Proofs.P3.JBootQ{g}\n')
    t = sub1(t, '\nnamespace Fl4Proofs.P3.JBoot\n', '\nnamespace Fl4Proofs.P3.JBootQ\nopen Fl4Proofs.P3.JBoot\n')
    t = sub1(t, '\nend Fl4Proofs.P3.JBoot\n', '\nend Fl4Proofs.P3.JBootQ\n')
    t = t.replace('JBoot.tcbZ', 'JBootQ.tcbZ')
    assert t.startswith('/-\n')
    t = ('/-\n**p3J gen 7 copy** of JBoot%s (namespace `JBootQ`, generated by scratch/p3J/genQ.py): the same proofs at\n'
         '`JBootQ.w0` / `JBootQ.fInitASt` (FL4\'s boot IRQ layout: line 125 `IRQ_TIMER`, 126 / 127 `IRQ_IPI`; spec 125\n'
         '`irqTimer`, 126 / 127 `irqReserved`). Original docstring:\n\n' % f) + t[3:]
    if f == 'Char':
        t = sub1(t, '  { (initASt (Z := Unit)) with kheap := kh, interruptIrqNode := N }\n',
                 '  { (initASt (Z := Unit)) with kheap := kh, interruptIrqNode := N, interruptStates := ipiIS }\n')
        t = sub1(t, '''theorem initASt_eq :
    (initASt (Z := Unit)) = bootSt initKheap (fun irq => initIrqNodePtr + (ucast 64 irq <<< cteLevelBits)) := rfl
''', '')
    if f == 'Mem':
        t = sub1(t, '  if a = 18446744071562096752 then mpW else 0#u64\n',
                 '  if a = 18446744071562096752 then mpW else\n'
                 f'  if a = {A[0]} then 2#u64 else\n  if a = {A[1]} then 3#u64 else\n  if a = {A[2]} then 3#u64 else 0#u64\n')
        t = sub1(t, '    (h16 : a ≠ 18446744071562096752) :\n',
                 f'    (h16 : a ≠ 18446744071562096752)\n    (h17 : a ≠ {A[0]})\n    (h18 : a ≠ {A[1]})\n'
                 f'    (h19 : a ≠ {A[2]}) :\n')
        t = sub1(t, 'if_neg h15, if_neg h16]', 'if_neg h15, if_neg h16, if_neg h17, if_neg h18, if_neg h19]')
        old = t[t.index('/-- **`IrqRel` at the witness**'):t.index('/-- **`IoRel` at the witness**')]
        t = t.replace(old, P('scratch/p3J/Qirq.lean').read_text())
    (D / f'JBootQ{f}.lean').write_text(t)
print('ok')
