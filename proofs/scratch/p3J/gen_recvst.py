# p3J gen 31: the endpoint receive at a resumed entry, stable ghosts.
# Generates P3/P3JRecvSt{A,B,C,D}.lean: the JAt-post sub-leaves of XTopJointRecvIpcLink's jRecvIpcU_of, proofs
# verbatim, named `…St`, post `RelTopM ∧ JStab Z H Cs` (every `RJ (L := L) arI AR r.1 r.2 z.2` replaced), final
# packaging `⟨…, _, _, _, _, _, _, J, inferInstance⟩` ↦ `⟨…, _, _, _, _, _, J⟩`. Usage: gen_recvst.py <proofs dir>
import re, sys
P = sys.argv[1] + '/Fl4Proofs/P3/'
STOP = ('set_option', '/--', 'theorem ', 'def ', 'end', 'section', 'variable', 'abbrev', 'lemma', 'private',
        'open', 'namespace', 'noncomputable', '@[', 'macro', 'instance', 'structure')
MODS = {
 'A': ('the blocking / polling / active-notification receives',
       [('XTopJointRecvIpcBlock', ['recvIpcBlockJG', 'recvIpcBlockJ']), ('XTopJointRecvIpcRet', ['recvIpcRetJ']),
        ('XTopJointRecvIpcBound', ['recvIpcBlockNJG', 'recvIpcBlockNJ']), ('XTopJointRecvIpc', ['recvIpcPollJR', 'recvIpcPollJ', 'recvIpcPollNJ']),
        ('XTopJointRecvIpcAct', ['recvIpcActJ'])], []),
 'B': ('the waiting-sender receives without a donation',
       [('XTopJointRecvSend', ['recvSendJG']), ('XTopJointRecvSendF', ['recvSendFJG', 'recvSendJX', 'recvSendJ0X']),
        ('XTopJointRecvSendRet', ['recvSendRetJ']), ('XTopJointRecvSendP', ['recvSendFPJG', 'recvSendPJG', 'recvSendP0X']),
        ('XTopJointRecvSendRP', ['recvSendRetPJ'])], []),
 'C': ('the waiting-sender receives donating the sender\'s SC',
       [('XTopJointRecvSendRD', ['recvSendFPDJ', 'recvSendPDJ', 'recvSendRetPDJ'])], ['B']),
 'D': ('the waiting-sender receives with a timeout fault',
       [('XTopJointRecvSendT', ['recvSendFTJ', 'recvSendFPTJ', 'recvSendT0X', 'recvSendRetTJ'])], ['B']),
}
ALL = [n for m in MODS.values() for _, ns in m[1] for n in ns]
RJ = 'RJ (L := L) arI AR r.1 r.2 z.2'
ST = 'RelTopM (L := L) r.1 z.2 ∧ JStab (L := L) arI AR Z H Cs r.1 r.2 z.2'
def block(src, start):
    i = next(k for k, l in enumerate(src) if l.startswith(start))
    j = i
    while src[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(src) and not src[k].startswith(STOP):
        k += 1
    while src[k - 1].strip() == '':
        k -= 1
    # enclosing section's variable lines and the namespace's open line
    sec = max(x for x in range(i) if src[x].startswith('section'))
    var = []
    x = sec + 1
    while x < i:
        if src[x].startswith('variable'):
            var.append(src[x]); x += 1
            while x < i and src[x].startswith('  '):
                var.append(src[x]); x += 1
        else:
            x += 1
    opn = [src[y] for y in range(sec) if src[y].startswith('open fl4_core')][-1]
    return '\n'.join(src[j:k]), '\n'.join(var), opn
def fix(body, n):
    for m in ALL:
        body = re.sub(r'(?<=\.)' + m + r'\b', m + 'St', body)
    assert body.count(RJ) >= 1, n
    body = body.replace(RJ, ST)
    pat = re.compile(r'_, _, _, _, _, _, (J\w*), inferInstance⟩')
    body = pat.sub(r'_, _, _, _, _, \1⟩', body)
    assert 'inferInstance⟩' not in body, n
    body = body.replace('/-- ', '/-- (p3J gen 31; stable ghosts, `JStab`) ', 1)
    return body
for key, (what, items, deps) in MODS.items():
    out = []
    imps = ['Fl4Proofs.P3.StPostFault'] + ['Fl4Proofs.P3.' + f for f, _ in items] + ['Fl4Proofs.P3.P3JRecvSt' + d for d in deps]
    names = []
    for f, ns in items:
        src = open(P + f + '.lean').read().split('\n')
        for n in ns:
            b, var, opn = block(src, 'theorem JAtZ.' + n + ' ')
            out.append('section\n' + opn + '\n' + var + '\n\n' + fix(b, n) + '\n\nend\n')
            names.append('`JAtZ.%sSt` (%s)' % (n, f))
    hdr = ('/-\nP3 (p3J gen 31): **the endpoint receive at a resumed entry, stable ghosts: %s** (generated by\n'
           '`scratch/p3J/gen_recvst.py`, as gen 30\'s `gen_sigst.py` and stpost\'s `gen_recv.py`).\n\n'
           'The proofs of XTopJointRecvIpcLink\'s `jRecvIpcU_of` sub-leaves end in `RJ` (`JAt`, ghosts existential) but\n'
           'build their exit at the entry\'s `H` and `Cs` (at `Z.mv G V`). This file is those proofs verbatim, named `…St`,\n'
           'with the post `RelTopM ∧ JStab Z H Cs` (StPostFault) and the final packaging adjusted:\n\n' % what
           + '\n'.join('* ' + x for x in names) +
           '\n\nNo premise added; no sorry. New module; no existing statement changed.\n-/\n'
           + '\n'.join('import ' + m for m in imps) + '\nopen Aeneas Aeneas.Std Result\n\nnamespace Fl4Proofs.P3\n\nnoncomputable section\n\n')
    open(P + 'P3JRecvSt' + key + '.lean', 'w').write(hdr + '\n'.join(out) + '\nend\n\nend Fl4Proofs.P3\n')
    print(key, len(names), sum(o.count('\n') for o in out))
