#!/usr/bin/env python3
"""Port P3's boot lemmas at initASt to sigmaB (gen 34). Usage: port.py <proofs dir> <out file>"""
import re, sys, os, collections
P = sys.argv[1]; OUT = sys.argv[2]
INIT = re.compile(r'\b(initASt|initKheap|initIoc|initIrqNodePtr)\b')
DECL = re.compile(r'^(?:@\[[^\]]*\]\s*)?(?:private |protected |noncomputable )*(theorem|lemma|def|abbrev|instance|structure|inductive)\s+([^\s:({\[]+)')

def chunks(path):
    """Split a Lean file into top-level items: ('skel', line) or ('decl', name, text)."""
    lines = open(path).read().split('\n')
    items = []; i = 0; pend = []  # pending docstring/attr lines
    depth = 0
    def comment_delta(l):
        return l.count('/-') - l.count('-/')
    while i < len(lines):
        l = lines[i]
        if l.startswith('/--') or (l.startswith('/-') and not l.startswith('/-!')):
            # docstring / comment: gather until closed
            buf = [l]; d = comment_delta(l)
            while d > 0:
                i += 1; buf.append(lines[i]); d += comment_delta(lines[i])
            i += 1
            if buf[0].startswith('/--'):
                pend.extend(buf)
            else:
                items.append(('other', '\n'.join(buf)))
            continue
        if l.startswith('/-!'):
            buf = [l]; d = comment_delta(l)
            while d > 0:
                i += 1; buf.append(lines[i]); d += comment_delta(lines[i])
            i += 1; items.append(('other', '\n'.join(buf))); continue
        if (l.startswith('@[') and not DECL.match(l)) or (l.startswith('set_option ') and l.rstrip().endswith(' in')):
            pend.append(l); i += 1; continue
        m = DECL.match(l)
        if m:
            buf = pend + [l]; pend = []; i += 1
            while i < len(lines) and (lines[i] == '' or lines[i][0] in ' \t)|'):
                buf.append(lines[i]); i += 1
            while buf and buf[-1] == '': buf.pop()
            items.append(('decl', m.group(2), '\n'.join(buf), m.group(1)))
            continue
        if pend:
            items.append(('other', '\n'.join(pend))); pend = []
        items.append(('skel', l)); i += 1
    return items

files = []
for root, _, fs in os.walk(os.path.join(P, 'Fl4Proofs/P3')):
    for f in fs:
        if f.endswith('.lean'): files.append(os.path.join(root, f))
parsed = {f: chunks(f) for f in files}
# family closure by short name
fam = set()
for f, its in parsed.items():
    for it in its:
        if it[0] == 'decl' and INIT.search(it[2]): fam.add(it[1].split('.')[-1])
changed = False
while changed:
    changed = False
    for f, its in parsed.items():
        for it in its:
            if it[0] == 'decl' and it[1].split('.')[-1] not in fam:
                body = it[2]
                toks = set(re.findall(r"[A-Za-z_][A-Za-z0-9_'!?.]*", body))
                short = {t.split('.')[-1] for t in toks}
                if short & fam:
                    # only count references in body after the name
                    fam.add(it[1].split('.')[-1]); changed = True
print('family', len(fam), file=sys.stderr)
# module import order: topological by imports
def mod_of(f): return os.path.relpath(f, P)[:-5].replace('/', '.')
imps = {}
for f in files:
    imps[mod_of(f)] = [l.split()[1] for l in open(f) if l.startswith('import ')]
fammods = [mod_of(f) for f, its in parsed.items() if any(it[0] == 'decl' and it[1].split('.')[-1] in fam for it in its)]
order = []; seen = set()
def visit(m):
    if m in seen or m not in imps: return
    seen.add(m)
    for d in imps[m]: visit(d)
    order.append(m)
for m in sorted(fammods): visit(m)
order = [m for m in order if m in fammods]
def rn(name): return name + '_B'
REPL = [(re.compile(r'\bFl4Spec\.(initASt|initKheap|initIoc|initIrqNodePtr)\b'), r'\1'), (re.compile(r'\binitASt\b'), 'σB'), (re.compile(r'\binitKheap\b'), 'kheapB'),
        (re.compile(r'\binitIoc\b'), 'iocB'), (re.compile(r'\binitIrqNodePtr\b'), 'irqNodeB')]
TOK = re.compile(r"(?<![A-Za-z0-9_'.])((?:[A-Za-z_][A-Za-z0-9_']*\.)*)([A-Za-z_][A-Za-z0-9_'!?]*)(?![A-Za-z0-9_'!?])")
def rename(text):
    for r, s in REPL: text = r.sub(s, text)
    def sub(m):
        parts = m.group(0).split('.')
        return '.'.join(rn(p) if p in fam else p for p in parts)
    return TOK.sub(sub, text)
out = []
out.append('/- generated by port.py -/')
out.append('import Fl4Proofs.P2.BootSpec')
for m in order: out.append('import ' + m)
out.append('open Aeneas Aeneas.Std Result')
out.append('open Fl4Proofs.P2.BootSt')
out.append('')
count = 0
for m in order:
    f = os.path.join(P, m.replace('.', '/') + '.lean')
    stack = []  # list of (kind, name, [skel lines])
    cur = []
    out.append(f'/-! ## from {m} -/')
    lastctx = False
    for it in parsed[f]:
        if it[0] != 'skel': lastctx = False
        if it[0] == 'skel':
            l = it[1].strip()
            wasctx = lastctx; lastctx = False
            if l.startswith('namespace '):
                stack.append(('ns', l.split()[1], []))
            elif l.startswith('noncomputable section') or l == 'section' or l.startswith('section '):
                stack.append(('sec', l.split()[-1] if l.startswith('section ') else '', []))
            elif l.startswith('end'):
                if stack: stack.pop()
            elif l.startswith('open ') or l.startswith('variable') or l.startswith('set_option') or l.startswith('attribute') or l.startswith('universe') or l.startswith('include ') or l.startswith('omit '):
                lastctx = True
                if stack: stack[-1][2].append(rename(it[1]))
                else: cur.append(rename(it[1]))
            elif l and wasctx and it[1][0] in ' \t' and not l.startswith('--'):
                lastctx = True
                # continuation line of variable etc
                if stack and stack[-1][2]: stack[-1][2][-1] += '\n' + it[1]
        elif it[0] == 'decl' and it[1].split('.')[-1] in fam:
            count += 1
            body = rename(it[2])
            # emit context
            hdr = []; ftr = []
            hdr.extend(cur)
            for k, n, ls in stack:
                if k == 'ns': hdr.append(f'namespace {n}'); ftr.insert(0, f'end {n}')
                else: hdr.append('section'); ftr.insert(0, 'end')
                hdr.extend(ls)
            out.append('section')
            out.extend(hdr)
            out.append(body)
            out.extend(ftr)
            out.append('end')
            out.append('')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('decls', count, 'modules', len(order), file=sys.stderr)
print('\n'.join(sorted(fam)), file=open(OUT + '.fam', 'w'))
