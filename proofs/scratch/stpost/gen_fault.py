# stpost: generate P3/StPostFault.lean, stable-ghost copies of the handle_fault arms
# (XTopJointNoFault's noFaultJ, XTopJointFaultG's faultBlockJG .. faultHypJZG).
import re, sys
P = sys.argv[1]  # proofs/Fl4Proofs/P3
nf = open(P + '/XTopJointNoFault.lean').read().split('\n')
fg = open(P + '/XTopJointFaultG.lean').read().split('\n')

def block(lines, start_pat, end_line_pat):
    # from the 'set_option' line before the theorem start to the line before end
    i = next(k for k, l in enumerate(lines) if l.startswith(start_pat))
    j = i
    while not lines[j - 1].startswith('set_option') and not lines[j-1].startswith('/--'):
        j -= 1
    # include docstring/set_option above
    while j > 0 and lines[j - 1].strip() != '' and not lines[j-1].startswith('theorem') and not lines[j-1].startswith('  '):
        j -= 1
    k = i + 1
    while k < len(lines) and not re.match(end_line_pat, lines[k]):
        k += 1
    return lines[j:k]

nofault = block(nf, 'theorem JAtZ.noFaultJ ', r'^(/--|set_option|theorem|def|end)')
# FaultG: from faultBlockJG to the end of faultHypJZG
i0 = next(k for k, l in enumerate(fg) if l.startswith('theorem JAtZ.faultBlockJG '))
while fg[i0 - 1].strip() != '':
    i0 -= 1
i1 = next(k for k, l in enumerate(fg) if l.startswith('theorem JAtZ.faultHypJZG '))
i1 = next(k for k in range(i1, len(fg)) if fg[k].strip() == 'end')
faultg = fg[i0:i1]

body = '\n'.join(nofault + [''] + faultg)
names = ['noFaultJ', 'faultBlockJG', 'sendFaultIJG', 'sendFaultPJG', 'sendFaultPDJG', 'faultRecvJG', 'faultHypJZG']
for n in names:
    body = re.sub(r'\b' + n + r'\b', n + 'St', body)
body = body.replace('JAt (L := L) arI AR ', 'JStab (L := L) arI AR Z H Cs ')
body = body.replace('⟨_, _, _, _, _, _, J7, inferInstance⟩', '⟨_, _, _, _, _, J7⟩')
body = body.replace('⟨_, H, Cs, Ac, Lst, D \\ {ptr}, J\', inferInstance⟩', '⟨_, _, Ac, Lst, D \\ {ptr}, J\'⟩')
body = body.replace('⟨Z, H, Cs, Ac, Lst\', D, J6, inferInstance⟩', '⟨Z.G, Z.vs, Ac, Lst\', D, J6⟩')
body = body.replace('obtain ⟨Z\', H\', Cs\', Ac\', Lst\', D\', J\', _⟩ := hJ', 'obtain ⟨G\', V\', Ac\', Lst\', D\', J\'⟩ := hJ')
body = body.replace('⟨_, _, _, _, _, _, J\', inferInstance⟩', '⟨_, _, _, _, _, J\'⟩')
body = body.replace('/-- **', '/-- (stable ghosts, `JStab`) **')

head = '''/-
P3 (line stpost): **`handle_fault` at `J` with the stable-ghost post**.

`JStab Z H Cs`: `JAtZ (Z.mv G V) H Cs …` for some MDB ghost `G` and VSpace sets `V` (the typed
heap `Z.th`, the buffer words `Z.B`, the heap `H` and the core set `Cs` kept). The posts of
XTopJointNoFault's `JAtZ.noFaultJ` and XTopJointFaultG's `JAtZ.faultBlockJG`, `sendFaultIJG`,
`sendFaultPJG`, `sendFaultPDJG`, `faultRecvJG`, `faultHypJZG` say only `JAt` (ghosts
existential), but every one of them builds its exit `JAtZ` at `Z.mv Z.G V'` (or `Z`) with the
entry's `H` and `Cs`. This file is those proofs verbatim (generated by
`scratch/stpost/gen_fault.py`), named `…St`, with `JAt` replaced by `JStab Z H Cs` and the
final packaging adjusted. No premise added.
-/
import Fl4Proofs.P3.XTopJointFaultG
open Aeneas Aeneas.Std Result

namespace Fl4Proofs.P3
open fl4_core Classical Fl4Proofs.P3.Vs Fl4Proofs.P1 Fl4Proofs.P3.Notif Fl4Proofs.P3.Endp Fl4Proofs.P3.Ipc
  Fl4Proofs.P3.Sched

noncomputable section

section
variable {S : Type} {st : machine.Store S} [L : P1.LawfulStore st] {A : Type}

/-- **The joint relation at stable ghosts** (module docstring): `JAtZ` at `Z.mv G V` with the
given `H` and `Cs`. -/
def JStab (arI : machine.Arch A) (AR : A → Fl4Spec.Cr3 → Prop) (Z : XSets) (H : P1.Heap) (Cs : Set U64)
    (s : S) (a : A) (σ : Fl4Spec.State Unit) : Prop :=
  ∃ (G : MdbGhost) (V : XVs) (Ac : Set U64) (Lst : U64 → List U64) (D : Set U64),
    JAtZ (L := L) arI AR (Z.mv G V) H Cs Ac Lst D s a σ

end

section
variable {S : Type} {st : machine.Store S} [L : P1.LawfulStore st] {A : Type} {arI : machine.Arch A}
variable {AR : A → Fl4Spec.Cr3 → Prop} {Z : XSets} {H : P1.Heap} {Cs Ac : Set U64}
  {Lst : U64 → List U64} {D : Set U64} {s : S} {a : A} {σ : Fl4Spec.State Unit}

'''
tail = '''
end

end

end Fl4Proofs.P3
'''
open(P + '/StPostFault.lean', 'w').write(head + body + tail)
