# stpost gen 7: the interrupt entry at stable ghosts.
# Generates P3/StPostIrqEv.lean from XTopJointKEntryEv2's `jEvRef_irq` and XTopJointKEntryEv6's `jEvRef_irqI` /
# `jEvRef_irqA` (proofs verbatim, StPostIrqLeaf's `…St` leaves, `jat_finishJRNMSt`, post `RJM ∧ JStab Z H Cs`).
# usage: python3 gen_irqev.py <proofs/Fl4Proofs/P3> <out.lean>
import sys
P = sys.argv[1]

def block(fname, start):
    src = open(P + '/' + fname).read().split('\n')
    i = next(k for k, l in enumerate(src) if l.startswith(start))
    j = i
    while src[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(src) and not src[k].startswith(('set_option', '/--', 'theorem ', 'def ', 'end', 'section', 'variable', 'open ')):
        k += 1
    while src[k - 1].strip() == '':
        k -= 1
    return '\n'.join(src[j:k])

def rep(body, old, new, n=1):
    c = body.count(old)
    assert c == n, (old, c)
    return body.replace(old, new)

POST_OLD = "      ∃ σ', EvOut false .interrupt σ σ' ∧ RJM (L := L) arI AR MR r.1 r.2 σ' ⦄ := by"
POST_NEW = ("      ∃ σ', EvOut false .interrupt σ σ' ∧ RJM (L := L) arI AR MR r.1 r.2 σ' ∧\n"
            "        JStab (L := L) arI AR Z H Cs r.1 r.2 σ' ⦄ := by")

def ev(b, name, ut):
    b = rep(b, 'theorem %s ' % name, 'theorem %sSt ' % name)
    b = rep(b, POST_OLD, POST_NEW)
    b = rep(b, "J0'.%s " % ut, "J0'.%sSt " % ut)
    b = rep(b, "rintro ⟨b, s2, a2⟩ ⟨⟨⟨z, hz, -, Z2, Ac2, Lst2, D2, J2, _⟩, hM2⟩, heq1⟩",
            "rintro ⟨b, s2, a2⟩ ⟨⟨⟨z, hz, -, G2, V2, Ac2, Lst2, D2, J2⟩, hM2⟩, heq1⟩")
    b = rep(b, "J3.handleIrqJIM hARI", "J3.handleIrqJIMSt hARI")
    b = rep(b, "rcases hP with hin | ⟨z', hz', ⟨Z3, H3, Cs3, Ac3, Lst4, D3, J4, _⟩, hM3⟩",
            "rcases hP with hin | ⟨z', hz', ⟨G3, V3, Ac3, Lst4, D3, J4⟩, hM3⟩")
    b = rep(b, "hFin _ hx Z3 H3 Cs3 Ac3 Lst4 D3 s3 a3 hfr J4.toR", "hFin _ hx _ H Cs Ac3 Lst4 D3 s3 a3 hfr J4.toR")
    b = rep(b, "WP.spec_mono (jat_finishJRNM s3", "WP.spec_mono (jat_finishJRNMSt s3")
    b = rep(b, "fun r ⟨σ', hmem, hRJ, hM'⟩ => ⟨σ', mem_kcall hx hmem, hRJ, hM'⟩",
            "fun r ⟨σ', hmem, hRJ, hM', hSt⟩ => ⟨σ', mem_kcall hx hmem, ⟨hRJ, hM'⟩, hSt.mv.mv⟩")
    return b

a = ev(block('XTopJointKEntryEv2.lean', 'theorem jEvRef_irq '), 'jEvRef_irq', 'utCheckB')
a = rep(a, "/-- **`JEvRef` of the interrupt entry from a non-idle thread**",
        "/-- (stable ghosts, `JStab`) **Ev2's `jEvRef_irq`**: `JEvRef` of the interrupt entry from a non-idle thread")
b = ev(block('XTopJointKEntryEv6.lean', 'theorem jEvRef_irqI '), 'jEvRef_irqI', 'utCheckBI')
b = rep(b, "/-- **The interrupt entry in the idle thread**", "/-- (stable ghosts, `JStab`) **The interrupt entry in the idle thread**")
c = block('XTopJointKEntryEv6.lean', 'theorem jEvRef_irqA ')
c = rep(c, 'theorem jEvRef_irqA ', 'theorem jEvRef_irqASt ')
c = rep(c, POST_OLD, POST_NEW)
c = rep(c, "/-- **The interrupt entry from any current thread**", "/-- (stable ghosts, `JStab`) **The interrupt entry from any current thread**")
c = rep(c, "exact jEvRef_irqI J", "exact jEvRef_irqISt J")
c = rep(c, "exact jEvRef_irq J", "exact jEvRef_irqSt J")

