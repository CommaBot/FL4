# stpost gen 6: the SetTimer label of the Thread cap at stable ghosts.
# Generates P3/StPostTmLeaf.lean from XTopJointTcb's `tcb_set_timerJ` (proof verbatim, post
# `JStab Z H Cs` instead of `JAt`, the two packings `J.stab` / `J2.stab`).
# usage: python3 gen_tm.py <proofs/Fl4Proofs/P3> <out.lean>
import sys
P = sys.argv[1]

def block(fname, start):
    src = open(P + '/' + fname).read().split('\n')
    i = next(k for k, l in enumerate(src) if l.startswith(start))
    j = i
    while src[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(src) and not src[k].startswith(('set_option', '/--', 'theorem ', 'def ', 'end', 'section', 'variable', 'open ')):
        k += 1
    while src[k - 1].strip() == '':
        k -= 1
    return '\n'.join(src[j:k])

def rep(body, old, new, n=1):
    c = body.count(old)
    assert c == n, (old, c)
    return body.replace(old, new)

b = block('XTopJointTcb.lean', 'theorem tcb_set_timerJ ')
b = rep(b, 'theorem tcb_set_timerJ ', 'theorem tcb_set_timerJSt ')
b = rep(b, '/-- **The SetTimer label at `JAt`**', '/-- (stable ghosts, `JStab`) **The SetTimer label at `J`**')
b = rep(b, '    TcbOKX (L := L) arI (JAt (L := L) arI AR) s ar σ fl4_abi.label.TCBSetTimer',
        '    TcbOKX (L := L) arI (JStab (L := L) arI AR Z H Cs) s ar σ fl4_abi.label.TCBSetTimer')
b = rep(b, '  have hJ0 : JAt (L := L) arI AR s ar σ := ⟨Z, H, Cs, Ac, Lst, D, J, inferInstance⟩',
        '  have hJ0 : JStab (L := L) arI AR Z H Cs s ar σ := J.stab')
b = rep(b, '⟨Z, H, Cs, Ac1, Lst1, D1 \\ {p}, J2, inferInstance⟩', 'J2.stab')

