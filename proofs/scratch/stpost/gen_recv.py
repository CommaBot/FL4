# stpost gen 4: the blocking endpoint receive under a pending switch, stable ghosts.
# Generates the body of P3/StPostRecvBlk.lean from XTopJointRecvIpcBlockM's
# JAtZ.recvIpcBlockJGM and JAtZ.recvIpcBlockNJGM (proofs verbatim, post RelTopM ∧ JStabR Z H Cs).
import re, sys
P = sys.argv[1]
src = open(P + '/XTopJointRecvIpcBlockM.lean').read().split('\n')
want = ['theorem JAtZ.recvIpcBlockJGM ', 'theorem JAtZ.recvIpcBlockNJGM ']
def block(start):
    i = next(k for k, l in enumerate(src) if l.startswith(start))
    j = i
    while src[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(src) and not src[k].startswith(('set_option', '/--', 'theorem ', 'def ', 'end', 'section', 'variable')):
        k += 1
    while src[k - 1].strip() == '':
        k -= 1
    return src[j:k]
body = '\n\n'.join('\n'.join(block(w)) for w in want)
for n in ['recvIpcBlockJGM', 'recvIpcBlockNJGM']:
    body = re.sub(r'(?<![\w])' + n + r'\b', n + 'St', body)
body = re.sub(r'(?<![\w.])SKeep\b', 'Ipc.SKeep', body)
body = body.replace('RJR (L := L) arI AR r.1 r.2 z.2',
                    'RelTopM (L := L) r.1 z.2 ∧ JStabR (L := L) arI AR Z H Cs r.1 r.2 z.2')
old = '⟨_, Set.mem_singleton _, J3.xtop.relTop, _, _, _, _, _, _, J3, inferInstance⟩'
assert body.count(old) == 1
body = body.replace(old, '⟨_, Set.mem_singleton _, J3.xtop.relTop, _, _, _, _, _, J3⟩')
body = body.replace('/-- **', '/-- (stable ghosts, `JStabR`) **')
