#!/usr/bin/env python3
"""Generate proofs/Fl4Proofs/P0/Consts.lean (proofs/Fl4ProofsA64/P0 for
`--arch aarch64`, from Fl4CoreA64): the value of every constant that
Aeneas extracted as a `Result` computation, as a `step` lemma.

Rust constants such as `ks::NODES` are arithmetic over other constants, so
Aeneas turns them into `Result` values that could, in principle, overflow.
The lemmas state each value (found with `#eval`) and prove it by rewriting
the constants it uses and evaluating the rest in the kernel (`rfl`, no
`native_decide`). P0 proofs then step over constants like any other call.

Usage: gen_const_specs.py PROOFS_DIR [--arch x86_64|aarch64] [--reuse-values]

--reuse-values takes the values from the Consts.lean already there instead
of evaluating them with Lean (no build): it checks that regenerating gives
the same file.
"""
import re
import subprocess
import sys
from pathlib import Path

args = sys.argv[1:]
arch = "x86_64"
if "--arch" in args:
    i = args.index("--arch")
    arch = args[i + 1]
    del args[i:i + 2]
reuse = "--reuse-values" in args
args = [a for a in args if a != "--reuse-values"]
if len(args) != 1 or arch not in ("x86_64", "aarch64"):
    sys.exit(__doc__)
# Extraction library, its namespace, and the proof library P0 goes into.
CORE, CORE_NS, PROOFS = {
    "x86_64": ("Fl4Core", "fl4_core", "Fl4Proofs"),
    "aarch64": ("Fl4CoreA64", "fl4_core_a64", "Fl4ProofsA64"),
}[arch]
REGEN = "`cargo xtask gate`" if arch == "x86_64" else "`gen_const_specs.py PROOFS_DIR --arch aarch64`"

proofs = Path(args[0]).resolve()
funs = (proofs / f"{CORE}/Funs.lean").read_text()
out_path = proofs / f"{PROOFS}/P0/Consts.lean"

# def NAME : TYPE := BODY, up to the next blank line.
defs = {}
order = []
for m in re.finditer(r"(?:^|\]\s*)def ([A-Za-z0-9_.]+) : (Result )?(Std\.U64|Std\.U32|Std\.Usize|Bool)\s*:=(.*?)\n\n", funs, re.S | re.M):
    name, is_result, ty, body = m.group(1), bool(m.group(2)), m.group(3), m.group(4)
    defs[name] = (is_result, ty, body)
    order.append(name)

results = [n for n in order if defs[n][0]]

# Values, from the Lean evaluator, over the current extraction.
if reuse:
    old = dict(re.findall(r"theorem ([A-Za-z0-9_.']+)\.spec : \S+ ⦃ v => v = (\d+)#\w+ ⦄", out_path.read_text()))
    missing = [n for n in results if n not in old]
    if missing:
        sys.exit(f"gen_const_specs: --reuse-values: no value for {', '.join(missing)}")
    vals = [(format(int(old[n]), "x"), "") for n in results]
else:
    subprocess.run(["lake", "build", CORE], cwd=proofs, check=True, capture_output=True)
    probe = proofs / f"{PROOFS}/P0/ConstsProbe.lean"
    probe.parent.mkdir(parents=True, exist_ok=True)
    probe.write_text(f"import {CORE}.Funs\nopen Aeneas Aeneas.Std Result {CORE_NS}\n" + "".join(f"#eval {n}\n" for n in results))
    out = subprocess.run(["lake", "env", "lean", str(probe)], cwd=proofs, capture_output=True, text=True)
    probe.unlink()
    vals = re.findall(r"Aeneas\.Std\.Result\.ok \{ bv := 0x([0-9a-f]+)#(\d+) \}", out.stdout)
    if len(vals) != len(results):
        sys.exit(f"gen_const_specs: expected {len(results)} values, got {len(vals)}:\n{out.stdout}\n{out.stderr}")

suffix = {"Std.U64": "u64", "Std.U32": "u32", "Std.Usize": "usize"}
head = [
    f"-- GENERATED by xtask/scripts/gen_const_specs.py from {CORE}/Funs.lean.",
    f"-- Do not edit: {REGEN} regenerates it.",
    f"import {CORE}.Funs",
    "open Aeneas Aeneas.Std Result",
    "",
    f"namespace {PROOFS}.P0.Consts",
    f"open {CORE_NS}",
    "",
]
def direct_deps(n):
    body = defs[n][2]
    return [d for d in order if d != n and re.search(r"(?<![\w.])" + re.escape(d) + r"(?![\w.])", body)]


def plain_closure(n, seen=None):
    """Plain (non-Result) constants reachable from n through plain ones."""
    seen = set() if seen is None else seen
    for d in direct_deps(n):
        if not defs[d][0] and d not in seen:
            seen.add(d)
            plain_closure(d, seen)
    return seen


def const_proofs(n, lit):
    """Proofs to try, in order: step over the body (Result-valued
    dependencies by their own spec, generated earlier: Funs.lean lists
    definitions in dependency order), or, where `step*` leaves goals
    (bitwise operations, `u64::MAX`), evaluate the constant in the kernel
    (`rfl` or `decide`, unfolding the irreducible scalar operations)."""
    plain = sorted(plain_closure(n))
    simp = f"simp only [{', '.join(plain)}]; " if plain else ""
    return [
        f"  unfold {n}; {simp}step*",
        f"  rw [show {n} = ok {lit} by with_unfolding_all rfl]; exact (WP.spec_ok _).2 rfl",
        f"  rw [show {n} = ok {lit} by with_unfolding_all decide]; exact (WP.spec_ok _).2 rfl",
        # Bitwise expressions: compare the bit vectors, which simp evaluates.
        f"  unfold {n}; {simp}step*\n  apply {defs[n][1].split('.')[-1]}.bv_eq_imp_eq\n  simp_all <;> decide",
    ]


lits = {n: f"{int(hexv, 16)}#{suffix[defs[n][1]]}" for n, (hexv, _bits) in zip(results, vals)}
attempt = {}
if reuse:
    # The proof the file already uses for each constant.
    old_text = out_path.read_text()
    for n in results:
        for i, pr in enumerate(const_proofs(n, lits[n])):
            if f"theorem {n}.spec : {n} ⦃ v => v = {lits[n]} ⦄ := by\n{pr}\n" in old_text:
                attempt[n] = i


def render():
    lines = list(head)
    spans = {}
    for n in results:
        start = len(lines) + 1
        lines += [
            f"@[step] theorem {n}.spec : {n} ⦃ v => v = {lits[n]} ⦄ := by",
            const_proofs(n, lits[n])[attempt.get(n, 0)],
            "",
        ]
        spans[n] = (start, len(lines))
    lines += plain_lines
    lines.append(f"end {PROOFS}.P0.Consts")
    return "\n".join(lines) + "\n", spans


plain_lines = []
# Plain (non-Result) constants: their values as simp lemmas, so goals such
# as `↑ASID_LOW_BITS < 64` close by simp or scalar_tac.
def plain_value(n):
    """The value of a plain constant: a literal or another plain constant."""
    is_result, ty, body = defs[n]
    b = body.strip()
    if is_result or ty not in suffix:
        return None
    if re.fullmatch(r"\d+#(u64|u32|usize)", b):
        return int(b.split("#")[0])
    if b in defs:
        return plain_value(b)
    return None


for n in order:
    v = plain_value(n)
    if v is None:
        continue
    b = defs[n][2].strip()
    proof = f"unfold {n}; rfl" if b not in defs else f"unfold {n}; exact {b}.val_eq"
    plain_lines += [
        f"@[simp, scalar_tac_simps] theorem {n}.val_eq : {n}.val = {v} := by",
        f"  {proof}",
        "",
    ]
out_path.parent.mkdir(parents=True, exist_ok=True)
for round_ in range(0 if reuse else 4):
    text, spans = render()
    out_path.write_text(text)
    r = subprocess.run(["lake", "env", "lean", str(out_path)], cwd=proofs, capture_output=True, text=True)
    bad = set()
    for m in re.finditer(r"Consts\.lean:(\d+):\d+: error", r.stdout + r.stderr):
        line = int(m.group(1))
        hit = [n for n, (a, b) in spans.items() if a <= line < b]
        if not hit:
            sys.exit("gen_const_specs: error outside a constant's proof:\n" + (r.stdout + r.stderr)[:4000])
        bad.add(hit[0])
    if not bad:
        if r.returncode != 0:
            sys.exit("gen_const_specs: Lean failed:\n" + (r.stdout + r.stderr)[:4000])
        break
    stuck = [n for n in bad if attempt.get(n, 0) + 1 >= len(const_proofs(n, lits[n]))]
    if stuck:
        sys.exit("gen_const_specs: no proof for " + ", ".join(sorted(stuck)) + ":\n" + (r.stdout + r.stderr)[:4000])
    for n in bad:
        attempt[n] = attempt.get(n, 0) + 1
    print(f"gen_const_specs: round {round_}: {len(bad)} proofs failed", file=sys.stderr)
else:
    if not reuse:
        sys.exit("gen_const_specs: no progress")
if reuse:
    out_path.write_text(render()[0])
print(f"gen_const_specs: {len(results)} constants")
