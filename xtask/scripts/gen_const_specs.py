#!/usr/bin/env python3
"""Generate proofs/Fl4Proofs/P0/Consts.lean: the value of every constant that
Aeneas extracted as a `Result` computation, as a `step` lemma.

Rust constants such as `ks::NODES` are arithmetic over other constants, so
Aeneas turns them into `Result` values that could, in principle, overflow.
The lemmas state each value (found with `#eval`) and prove it by rewriting
the constants it uses and evaluating the rest in the kernel (`rfl`, no
`native_decide`). P0 proofs then step over constants like any other call.

Usage: gen_const_specs.py PROOFS_DIR
"""
import re
import subprocess
import sys
from pathlib import Path

proofs = Path(sys.argv[1]).resolve()
funs = (proofs / "Fl4Core/Funs.lean").read_text()

# def NAME : TYPE := BODY, up to the next blank line.
defs = {}
order = []
for m in re.finditer(r"(?:^|\]\s*)def ([A-Za-z0-9_.]+) : (Result )?(Std\.U64|Std\.U32|Std\.Usize|Bool)\s*:=(.*?)\n\n", funs, re.S | re.M):
    name, is_result, ty, body = m.group(1), bool(m.group(2)), m.group(3), m.group(4)
    defs[name] = (is_result, ty, body)
    order.append(name)

results = [n for n in order if defs[n][0]]

# Values, from the Lean evaluator.
probe = proofs / "Fl4Proofs/P0/ConstsProbe.lean"
probe.write_text("import Fl4Core.Funs\nopen Aeneas Aeneas.Std Result fl4_core\n" + "".join(f"#eval {n}\n" for n in results))
out = subprocess.run(["lake", "env", "lean", str(probe)], cwd=proofs, capture_output=True, text=True)
probe.unlink()
vals = re.findall(r"Aeneas\.Std\.Result\.ok \{ bv := 0x([0-9a-f]+)#(\d+) \}", out.stdout)
if len(vals) != len(results):
    sys.exit(f"gen_const_specs: expected {len(results)} values, got {len(vals)}:\n{out.stdout}\n{out.stderr}")

suffix = {"Std.U64": "u64", "Std.U32": "u32", "Std.Usize": "usize"}
lines = [
    "-- GENERATED by xtask/scripts/gen_const_specs.py from Fl4Core/Funs.lean.",
    "-- Do not edit: `cargo xtask gate` regenerates it.",
    "import Fl4Core.Funs",
    "open Aeneas Aeneas.Std Result",
    "",
    "namespace Fl4Proofs.P0.Consts",
    "open fl4_core",
    "",
]
def direct_deps(n):
    body = defs[n][2]
    return [d for d in order if d != n and re.search(r"(?<![\w.])" + re.escape(d) + r"(?![\w.])", body)]


def plain_closure(n, seen=None):
    """Plain (non-Result) constants reachable from n through plain ones."""
    seen = set() if seen is None else seen
    for d in direct_deps(n):
        if not defs[d][0] and d not in seen:
            seen.add(d)
            plain_closure(d, seen)
    return seen


for n, (hexv, _bits) in zip(results, vals):
    ty = defs[n][1]
    plain = sorted(plain_closure(n))
    lit = f"{int(hexv, 16)}#{suffix[ty]}"
    simp = f"simp only [{', '.join(plain)}]; " if plain else ""
    # Result-valued dependencies are stepped over with their own spec,
    # generated earlier (Funs.lean lists definitions in dependency order).
    lines += [
        f"@[step] theorem {n}.spec : {n} ⦃ v => v = {lit} ⦄ := by",
        f"  unfold {n}; {simp}step*",
        "",
    ]
# Plain (non-Result) constants: their values as simp lemmas, so goals such
# as `↑ASID_LOW_BITS < 64` close by simp or scalar_tac.
def plain_value(n):
    """The value of a plain constant: a literal or another plain constant."""
    is_result, ty, body = defs[n]
    b = body.strip()
    if is_result or ty not in suffix:
        return None
    if re.fullmatch(r"\d+#(u64|u32|usize)", b):
        return int(b.split("#")[0])
    if b in defs:
        return plain_value(b)
    return None


for n in order:
    v = plain_value(n)
    if v is None:
        continue
    b = defs[n][2].strip()
    proof = f"unfold {n}; rfl" if b not in defs else f"unfold {n}; exact {b}.val_eq"
    lines += [
        f"@[simp, scalar_tac_simps] theorem {n}.val_eq : {n}.val = {v} := by",
        f"  {proof}",
        "",
    ]
lines.append("end Fl4Proofs.P0.Consts")
(proofs / "Fl4Proofs/P0/Consts.lean").write_text("\n".join(lines) + "\n")
print(f"gen_const_specs: {len(results)} constants")
